def find_top_level_paragraphs(doc):
    """返回 body 直接子级所有 <w:p> 的 (start, end) 区间，按文档顺序。

    需要同时处理三种写法：普通段落、自闭合空段落 <w:p/>、
    以及嵌套在图形（文本框/标注）内部的段落——后者必须被跳过。
    """
    sc_re = re.compile(r"<w:p(?: [^>]*[^/>])?/>")   # 自闭合空段落
    op_re = re.compile(r"<w:p(?: [^>]*[^/>])?>")    # 段落开标签
    cl_re = re.compile(r"</w:p>")

    tokens = []
    for m in sc_re.finditer(doc):
        tokens.append((m.start(), m.end(), "sc"))
    for m in op_re.finditer(doc):
        tokens.append((m.start(), m.end(), "op"))
    for m in cl_re.finditer(doc):
        tokens.append((m.start(), m.end(), "cl"))
    tokens.sort()

    spans, depth, start = [], 0, None
    for s, e, kind in tokens:
        if kind == "sc":
            if depth == 0:
                spans.append((s, e))
        elif kind == "op":
            if depth == 0:
                start = s
            depth += 1
        else:
            depth -= 1
            if depth == 0:
                spans.append((start, e))
    return spans


